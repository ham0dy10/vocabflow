function getLanguage(){
  const s = typeof getSettings === "function" ? getSettings() : {};
  return s.language || "en";
}
function setLanguage(lang){
  if(typeof saveSettings === "function") saveSettings({language: lang});
  applyTranslations();
  window.dispatchEvent(new CustomEvent("vocabflow:langchange", {detail:{lang}}));
}
function t(key){
  const lang = getLanguage();
  const dict = I18N[lang] || I18N.en;
  return dict[key] || I18N.en[key] || key;
}
window.t = t;

function applyTranslations(rootNode = document){
  const lang = getLanguage();
  const scope = rootNode && typeof rootNode.querySelectorAll === "function" ? rootNode : document;
  scope.querySelectorAll("[data-i18n]").forEach(el=>{
    el.textContent = t(el.dataset.i18n);
    // Language changes text only. Keep every UI element in the same LTR
    // position, alignment, and visual order in English and Arabic.
    el.dir = "ltr";
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach(el=>{
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
    el.dir = "ltr";
  });

  // A detached <main> used for SPA navigation must not mutate the live
  // document. The caller will sync the document after insertion.
  if (scope !== document) return;

  const root = document.documentElement;
  root.setAttribute("data-lang", lang);
  root.lang = lang;
  // Never mirror or flip the interface for Arabic.
  root.dir = "ltr";
  delete root.dataset.i18nPending;
  if(typeof window.applyThemeLabel === "function"){
    window.applyThemeLabel(document.documentElement.dataset.theme || "light");
  }
}

window.applyTranslationsTo = function(rootNode){
  applyTranslations(rootNode);
};

function setupLanguageToggle(){
  const btn = document.getElementById("langToggle");
  if(btn && !btn.dataset.bound){
    btn.dataset.bound = "1";
    btn.addEventListener("click", ()=>{
      const next = getLanguage() === "ar" ? "en" : "ar";
      setLanguage(next);
    });
  }
}

if(typeof document !== "undefined") document.addEventListener("vocabflow:pageinit", ()=>{
  applyTranslations();
  setupLanguageToggle();
});
